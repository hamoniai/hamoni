/**
 * Additional clean tasks
 */
val cleanNodeTask = project.tasks.register<Delete>("cleanNode") {
    val base = project.layout.projectDirectory.dir("../control-room-ui")
    delete(
        base.dir("node_modules"),
        base.dir("build"),
        base.dir("dist"),
        base.dir(".angular"),
    )
}
project.tasks.named("clean").configure {
    dependsOn(cleanNodeTask)
}

/**
 * Copy the schema migrations generated by the schema export command into the
 * project source tree.
 *
 * The export command deliberately writes to the build directory first, so a
 * failed export never leaves a partially overwritten migration in place.
 *
 * NOTE: the generated directory is not cleaned before an export yet. Once the
 * Quarkus schema-export start task is wired into Gradle, add a pre-start clean
 * task here so Gradle can track which files each task generated.
 */
val copySchemaMigrations = tasks.register<Copy>("copySchemaMigrations") {
    group = "schema"
    description = "Copy generated schema migrations into src/main/resources/db/migration."

    val generatedSchema = layout.buildDirectory.dir("generated/schema")

    from(generatedSchema)
    into(layout.projectDirectory.dir("src/main/resources/db/migration"))
    include("**/V*.sql")

    doFirst {
        if (!generatedSchema.get().asFile.exists()) {
            throw GradleException(
                "No generated schema found in ${generatedSchema.get().asFile}. " +
                    "Run the schema export command first."
            )
        }
    }
}
