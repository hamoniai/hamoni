/**
 * Behaviour of [SchemaExportCommand].
 */
class SchemaExportCommandTest {

    private val schemaExportService = mockk<SchemaExportService>()
    private val command = SchemaExportCommand(schemaExportService)

    @Test
    fun `the command exports both schemas and returns zero`() {
        // Given
        every { schemaExportService.export() } returns emptyList()

        // When
        val result = command.run()

        // Then
        assertThat(result).isZero()
        verify(exactly = 1) { schemaExportService.export() }
    }
}

/**
 * Behaviour of [SchemaExportService].
 */
class SchemaExportServiceTest {

    @TempDir
    lateinit var outputDirectory: Path

    private val sessionFactory = mockk<SessionFactory>()
    private val schemaManager = mockk<SchemaManager>()
    private val properties = mutableMapOf<String, Any>()

    @Test
    fun `both schema files are written with their own filter and header`() {
        // Given
        val appliedFilters = mutableListOf<Any?>()
        every { sessionFactory.schemaManager } returns schemaManager
        every { sessionFactory.properties } returns properties
        every { schemaManager.create(false) } answers {
            appliedFilters.add(properties[AvailableSettings.HBM2DDL_FILTER_PROVIDER])
            val writer = properties[AvailableSettings.JAKARTA_HBM2DDL_SCRIPTS_CREATE_TARGET] as Writer
            writer.write("-- body for ${appliedFilters.last()} --\n")
        }
        val service = SchemaExportService(sessionFactory, "1.0.0-SNAPSHOT", "h2", outputDirectory.toString())

        // When
        val files = service.export()

        // Then
        val platformFile = outputDirectory.resolve("platform/h2/V1.0.0__schema.sql").toAbsolutePath().normalize()
        val organisationFile = outputDirectory.resolve("organisation/h2/V1.0.0__schema.sql").toAbsolutePath().normalize()

        assertThat(files).containsExactly(platformFile, organisationFile)
        assertThat(platformFile).exists()
        assertThat(organisationFile).exists()
        assertThat(appliedFilters).containsExactly(
            PlatformSchemaFilterProvider::class.java.name,
            OrganisationSchemaFilterProvider::class.java.name
        )

        val platformContent = platformFile.toFile().readText()
        assertThat(platformContent)
            .contains("-- Generated by the Hamoni schema export command")
            .contains("-- Application version: 1.0.0-SNAPSHOT")
            .contains("-- Migration version: 1.0.0")
            .contains("-- Schema: platform")
            .contains("-- Database: h2")
            .contains("-- body for ${PlatformSchemaFilterProvider::class.java.name} --")
            .doesNotContain("-- Schema: organisation")

        val organisationContent = organisationFile.toFile().readText()
        assertThat(organisationContent)
            .contains("-- Generated by the Hamoni schema export command")
            .contains("-- Application version: 1.0.0-SNAPSHOT")
            .contains("-- Migration version: 1.0.0")
            .contains("-- Schema: organisation")
            .contains("-- Database: h2")
            .contains("-- body for ${OrganisationSchemaFilterProvider::class.java.name} --")
            .doesNotContain("-- Schema: platform")

        verify(exactly = 2) { schemaManager.create(false) }
    }

    @Test
    fun `the script and filter properties are configured for the export`() {
        // Given
        every { sessionFactory.schemaManager } returns schemaManager
        every { sessionFactory.properties } returns properties
        every { schemaManager.create(false) } answers {
            val writer = properties[AvailableSettings.JAKARTA_HBM2DDL_SCRIPTS_CREATE_TARGET] as Writer
            writer.write("-- generated --\n")
        }
        val service = SchemaExportService(sessionFactory, "1.0.0-SNAPSHOT", "h2", outputDirectory.toString())

        // When
        service.export()

        // Then
        assertThat(properties[AvailableSettings.JAKARTA_HBM2DDL_DATABASE_ACTION]).isEqualTo(Action.NONE)
        assertThat(properties[AvailableSettings.JAKARTA_HBM2DDL_SCRIPTS_ACTION]).isEqualTo(Action.CREATE_ONLY)
        assertThat(properties[AvailableSettings.FORMAT_SQL]).isEqualTo(true)
        assertThat(properties["${AvailableSettings.JAKARTA_HBM2DDL_DATABASE_ACTION}.orm"]).isEqualTo(Action.NONE)
        assertThat(properties["${AvailableSettings.JAKARTA_HBM2DDL_SCRIPTS_ACTION}.orm"]).isEqualTo(Action.CREATE_ONLY)
    }
}

/**
 * Behaviour of the application-version reduction.
 */
class FlywayVersionTest {

    @Test
    fun `a snapshot version is reduced to a Flyway version`() {
        // Given
        val applicationVersion = "1.0.0-SNAPSHOT"

        // When
        val migrationVersion = flywayVersion(applicationVersion)

        // Then
        assertThat(migrationVersion).isEqualTo("1.0.0")
    }

    @Test
    fun `a release version is unchanged`() {
        // Given
        val applicationVersion = "1.2.3"

        // When
        val migrationVersion = flywayVersion(applicationVersion)

        // Then
        assertThat(migrationVersion).isEqualTo("1.2.3")
    }

    @Test
    fun `a version without a numeric prefix is rejected`() {
        // Given
        val applicationVersion = "SNAPSHOT"

        // When / Then
        assertThatThrownBy { flywayVersion(applicationVersion) }
            .isInstanceOf(IllegalArgumentException::class.java)
    }
}
